#!/bin/sh
set -e
cd "$(dirname "$0")/.."
P=usr/lib/python3.12

V=usr/share/vim/vim91
K=
for f in syntax synload syncolor nosyntax manual python sh c cpp lua javascript typescript json html css \
  markdown vim yaml toml sql make diff conf dosini awk sed xml help text go rust java ruby php perl \
  dockerfile gitcommit gitconfig gitrebase man; do
  K="$K --keep $V/syntax/$f.vim"
done

python3 alpine.py micropython sqlite libpanelw jq htop bash nano nano-syntax micro lua5.4 tcc tcc-libs-static tcc-dev musl-dev \
  vim helix tmux fzf make ruby php83 perl janet \
  nodejs cmatrix sl figlet cbonsai nyancat \
  --skip mpdecimal --skip so:libmpdec.so.4 \
  --skip gdbm --skip so:libgdbm_compat.so.4 --skip so:libgdbm.so.6 --skip pkgconfig \
  --keep "usr/lib/tcc/*" \
  --drop "$V/doc/*" --drop "$V/spell/*" --drop "$V/pack/*" --drop "$V/tutor/*" --drop "$V/lang/*" \
  --drop "$V/print/*" --drop "$V/tools/*" --drop "$V/macros/*" --drop "$V/keymap/*" --drop "$V/syntax/*" \
  --drop "$V/*menu.vim" --drop "$V/mswin.vim" --drop "$V/evim.vim" --drop "$V/gvimrc_example.vim" \
  --keep "$V/syntax/shared/*" $K

python3 alpine.py musl-dev --keep "usr/lib/lib[!c]*.a" --keep "usr/lib/libcrypt.a"

scripts/build-python.sh

python3 alpine.py py3-pytelegrambotapi --skip py3-requests --skip python3
T=build/packages/py3-pytelegrambotapi/$P/site-packages/telebot
rm -rf $T/async_telebot.py $T/asyncio_* $T/ext/aio
sed -i 's/^import ssl$/try:\n    import ssl\nexcept ImportError:\n    ssl = None/' $T/__init__.py
rm -rf build/packages/python-telebot
mv build/packages/py3-pytelegrambotapi build/packages/python-telebot
echo "python3 python-requests" > build/packages/python-telebot/.deps

ln -sf micropython build/packages/micropython/usr/bin/py
echo "musl libffi" > build/packages/micropython/.deps
ln -sf lua5.4 build/packages/lua5.4/usr/bin/lua
echo "musl tcc-libs tcc-libs-static tcc-dev musl-dev" > build/packages/tcc/.deps
mkdir -p build/packages/tcc/usr/lib
ln -sfn . build/packages/tcc/usr/lib/i386-linux-gnu
mkdir -p build/packages/nano/etc/profile.d build/packages/nano/usr/share
rm -rf build/packages/nano/usr/share/nano
mv build/packages/nano-syntax/usr/share/nano build/packages/nano/usr/share/nano
rm -rf build/packages/nano-syntax build/packages/nano/usr/share/nano/extra
sed -i 's|^# include /usr/share/nano/\*\.nanorc$|include /usr/share/nano/*.nanorc|' build/packages/nano/etc/nanorc
echo "export EDITOR=nano" > build/packages/nano/etc/profile.d/nano.sh
mkdir -p build/packages/micro/etc/profile.d
echo "export EDITOR=micro" > build/packages/micro/etc/profile.d/micro.sh
ln -sf php83 build/packages/php83/usr/bin/php
rm -f build/packages/libevent/usr/lib/libevent_openssl*
echo "musl" > build/packages/libevent/.deps

# chawan есть только с v3.24. Его http/https/gemini/sftp - cgi-bin/ssl на openssl
# и сырых сокетах, а наружу из v86 ходит только fetch браузера: ssl и его библиотеки
# (~6 МБ в памяти) не берём, http и https даёт пакет chawan-fetch
C=usr/libexec/chawan/cgi-bin
python3 alpine.py chawan --branch v3.24 \
  --skip so:libssl.so.3 --skip so:libcrypto.so.3 --skip so:libssh2.so.1 --skip so:libbrotlidec.so.1 \
  --drop $C/ssl --drop $C/http --drop $C/https --drop $C/gemini --drop $C/sftp
echo "musl chawan-fetch" > build/packages/chawan/.deps

python3 alpine.py $(python3 scripts/pyset.py --skip py3-requests --skip py3-pip) py3-numpy py3-pandas py3-scipy py3-matplotlib \
  --keep-existing --alias py3-requests=python-requests --alias py3-pip=pip --alias py3-numpy=python-numpy --rename py3-:python-
mpl=build/packages/python-matplotlib/usr/lib/python3.12/site-packages
patch -d $mpl -p1 -R -s -f --dry-run < patches/matplotlib.patch > /dev/null 2>&1 || patch -d $mpl -p1 -s < patches/matplotlib.patch
# C-исходники, из которых Cython собрал лежащий рядом модуль (fontTools кладёт их в колесо): при работе не нужны.
# Свои .c у пакетов (Cython/Utility и т.п.) не сгенерированы Cython и остаются
find build/packages -path '*/site-packages/*' -name '*.c' | while read -r f; do
  if head -c 22 "$f" | grep -q '^/\* Generated by Cython' && ls "${f%.c}".*.so > /dev/null 2>&1; then rm "$f"; fi
done
# matplotlib берёт из qhull только libqhull_r, программы qconvex, qdelaunay и др. не нужны
rm -rf build/packages/qhull/usr/bin
scripts/build-openblas.sh
scripts/build-numpy.sh
scripts/build-doom.sh
# libdrm - одна libdrm.so.2 (100 КБ, ей нужна только musl): её берут Xorg и mesa-xlib (virgl). В пакете
# Alpine ещё библиотеки чужих видеокарт (amdgpu, intel, nouveau...), а с ними libpciaccess и база имён PCI
# (hwdata-pci, 1.5 МБ)
python3 alpine.py libdrm --keep-existing --max-age 168 --skip libpciaccess --drop 'usr/lib/libdrm_*'
scripts/build-xorg.sh
scripts/build-xclipd.sh
scripts/build-xwm.sh
scripts/build-dwm.sh
scripts/build-mesa.sh
# Демо OpenGL: glxinfo и glxgears (mesa-utils), mesa-demos (gloss, teapot, fire, terrain... ~290 программ) -
# только GLX через mesa-xlib: 3D на странице (virgl) или softpipe. Целиком они тянут mesa с LLVM (~250 МБ,
# машине не поставить) через EGL, GLES и GBM, ещё Vulkan и Wayland - программ для них (egl*, es2*,
# peglgears, xeglgears, vkgears) в пакетах нет
python3 alpine.py mesa-demos --keep-existing --max-age 168 --alias mesa-gl=mesa-xlib \
  --skip mesa-egl --skip mesa-gles --skip mesa-gbm --skip vulkan-loader --skip libdecor \
  --skip wayland-libs-client --skip wayland-libs-egl --skip libxkbcommon --skip libxkbcommon-x11 \
  --drop 'usr/bin/egl*' --drop 'usr/bin/es2*' --drop usr/bin/peglgears --drop usr/bin/xeglgears --drop usr/bin/vkgears
# Qt5 под X: libGL - наша mesa-xlib (у mesa из Alpine LLVM, ~480 МБ), без EGL/GBM (они - для платформ без X),
# GTK3 (тема), libinput, cups, pango, xdg-utils (тянет libmagic, 10 МБ), libdrm (её ставит xorg) и полных
# xkeyboard-config (раскладку Qt берёт у сервера) и ICU (хватает icu-data-en)
python3 alpine.py sqlitebrowser --keep-existing --max-age 168 --alias mesa-gl=mesa-xlib \
  --skip mesa-egl --skip mesa-gbm --skip gtk+3.0 --skip libinput-libs --skip cups-libs --skip pango \
  --skip xdg-utils --skip libdrm --skip xkeyboard-config --skip icu-data-full
# Qt Designer: из qt5-qttools-dev только designer (Qt5 - тот же, что у sqlitebrowser выше). Весь пакет -
# 91 пакет и ~925 МБ: libclang (LLVM 18) нужен лишь qdoc, qt5-qttools (Qt Quick) - qdbus/qtdiag,
# qt5-qtbase-dev (mesa-dev, perl, драйверы SQL) - заголовкам, libqt5help - qhelpgenerator
python3 alpine.py qt5-qttools-dev --keep-existing --max-age 168 --alias mesa-gl=mesa-xlib \
  --skip qt5-qttools --skip libqt5help --skip qt5-qtbase-dev --skip clang18-libclang --skip pkgconfig \
  --drop 'usr/include/*' --drop 'usr/lib/qt5/*' --drop 'usr/bin/*' --drop 'usr/lib/*.prl' \
  --drop 'usr/lib/libQt5*.so' --drop 'usr/share/applications/linguist*' \
  --keep 'usr/lib/qt5/bin/designer' --keep 'usr/bin/designer' --keep 'usr/bin/designer-qt5'
# PyQt5 для форм из Designer (uic.loadUi): модули на нашем Qt5 и QtSvg (0.3 МБ). Целиком py3-qt5 - ~490 МБ:
# мультимедиа (gstreamer, 370 МБ), карты, Bluetooth/NFC, QML, WebChannel/WebSockets, справка, X11Extras -
# их модулей в пакете нет, как и PyQt5.Qt (грузит всё сразу), .sip для сборки, OpenGL-функций (GL-контекста
# в нашем X нет), плагинов Designer и QML и dbus.mainloop (ему нужен dbus-python)
Q=$P/site-packages/PyQt5
D=
for m in Qt QtBluetooth QtNfc QtLocation QtPositioning QtMultimedia QtMultimediaWidgets QtQml QtQuick QtQuickWidgets \
  QtWebChannel QtWebSockets QtHelp QtSerialPort QtX11Extras _QOpenGLFunctions_2_0 _QOpenGLFunctions_2_1 \
  _QOpenGLFunctions_4_1_Core; do
  D="$D --drop $Q/$m.abi3.so"
done
python3 alpine.py py3-qt5 --keep-existing --max-age 168 --alias mesa-gl=mesa-xlib --rename py3-:python- \
  --skip qt5-qtconnectivity --skip qt5-qtlocation --skip qt5-qtmultimedia --skip qt5-qtdeclarative \
  --skip qt5-qtwebchannel --skip qt5-qtwebsockets-libs --skip libqt5help --skip qt5-qtserialport \
  --skip qt5-qtx11extras $D --drop "$Q/bindings/*" --drop 'usr/lib/qt5/plugins/designer/*' \
  --drop 'usr/lib/qt5/plugins/PyQt5/*' --drop 'usr/share/qt5/*' --drop "$P/site-packages/dbus/*"
python3 scripts/jdk8.py
